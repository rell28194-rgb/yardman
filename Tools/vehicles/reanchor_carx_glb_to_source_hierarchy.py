#!/usr/bin/env python3
"""Re-anchor a recovered CarX render GLB to an exact source hierarchy.

The older Yardman recovery exporter preserved useful mesh/material buffers but
flattened many Unity transforms and generated its own wheel pivots. This tool
keeps those recovered render buffers while replacing hierarchy authority with a
private descriptor generated by build_source_hierarchy_runtime.py.

No donor media is embedded in this script. Input/output GLBs remain private pack
artifacts.
"""

from __future__ import annotations

import argparse
import json
import struct
from pathlib import Path
from typing import Any

GENERATED_TO_SOURCE_WHEELS = {
    "FrontWheelLeft": "WheelFL",
    "FrontWheelRight": "WheelFR",
    "RearWheelLeft": "WheelRL",
    "RearWheelRight": "WheelRR",
}


def _read_glb(path: Path) -> tuple[dict[str, Any], list[tuple[bytes, bytes]]]:
    raw = path.read_bytes()
    magic, version, total = struct.unpack_from("<4sII", raw, 0)
    if magic != b"glTF" or version != 2 or total != len(raw):
        raise ValueError("input is not a valid GLB 2.0 file")
    offset = 12
    document: dict[str, Any] | None = None
    other_chunks: list[tuple[bytes, bytes]] = []
    while offset < len(raw):
        length, chunk_type = struct.unpack_from("<I4s", raw, offset)
        offset += 8
        data = raw[offset : offset + length]
        offset += length
        if chunk_type == b"JSON":
            document = json.loads(data.rstrip(b" \t\r\n\0"))
        else:
            other_chunks.append((chunk_type, data))
    if document is None:
        raise ValueError("GLB has no JSON chunk")
    return document, other_chunks


def _write_glb(path: Path, document: dict[str, Any], chunks: list[tuple[bytes, bytes]]) -> None:
    payload = json.dumps(document, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    payload += b" " * ((4 - len(payload) % 4) % 4)
    body = [struct.pack("<I4s", len(payload), b"JSON") + payload]
    for chunk_type, raw_data in chunks:
        data = raw_data + b"\0" * ((4 - len(raw_data) % 4) % 4)
        body.append(struct.pack("<I4s", len(data), chunk_type) + data)
    chunks_blob = b"".join(body)
    output = struct.pack("<4sII", b"glTF", 2, 12 + len(chunks_blob)) + chunks_blob
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(output)


def _single_node(nodes: list[dict[str, Any]], name: str) -> int:
    matches = [index for index, node in enumerate(nodes) if node.get("name") == name]
    if len(matches) != 1:
        raise ValueError(f"expected one node named {name!r}, found {matches}")
    return matches[0]


def _is_default(values: list[float], expected: list[float], epsilon: float = 1e-9) -> bool:
    return all(abs(float(a) - float(b)) < epsilon for a, b in zip(values, expected))


def _validate_single_parent(document: dict[str, Any]) -> tuple[int, int]:
    nodes = document.get("nodes", [])
    parents: dict[int, int] = {}
    for parent_index, node in enumerate(nodes):
        for child in node.get("children", []):
            child_index = int(child)
            if child_index < 0 or child_index >= len(nodes):
                raise ValueError(f"node {parent_index} references invalid child {child_index}")
            if child_index in parents:
                raise ValueError(
                    f"node {child_index} has multiple parents: {parents[child_index]} and {parent_index}"
                )
            parents[child_index] = parent_index

    scene_index = int(document.get("scene", 0))
    roots = document.get("scenes", [])[scene_index].get("nodes", [])
    visited: set[int] = set()
    active: set[int] = set()

    def walk(index: int) -> None:
        if index in active:
            raise ValueError(f"cycle detected at node {index}")
        if index in visited:
            return
        active.add(index)
        for child in nodes[index].get("children", []):
            walk(int(child))
        active.remove(index)
        visited.add(index)

    for root in roots:
        walk(int(root))
    return len(visited), len(nodes) - len(visited)


def reanchor(document: dict[str, Any], runtime: dict[str, Any]) -> dict[str, Any]:
    nodes: list[dict[str, Any]] = document.setdefault("nodes", [])
    if int(runtime.get("format_version", 0)) != 1:
        raise ValueError("unsupported source hierarchy runtime descriptor")

    # Find the old flattened render hierarchy before appending source nodes.
    old_root_name = str(runtime.get("identity", ""))
    old_root_index = _single_node(nodes, old_root_name)
    old_root = nodes[old_root_index]
    wheel_render: dict[str, dict[str, int]] = {}
    generated_root_indices: list[int] = []

    for generated_name, source_name in GENERATED_TO_SOURCE_WHEELS.items():
        generated_index = _single_node(nodes, generated_name)
        generated_root_indices.append(generated_index)
        generated_children = [int(value) for value in nodes[generated_index].get("children", [])]
        spin_name = generated_name + "Spin"
        spin_matches = [index for index in generated_children if nodes[index].get("name") == spin_name]
        caliper_matches = [
            index
            for index in generated_children
            if str(nodes[index].get("name", "")).startswith("Caliper")
        ]
        if len(spin_matches) != 1 or len(caliper_matches) != 1:
            raise ValueError(
                f"{generated_name} does not expose one caliper and one spin render subtree"
            )
        wheel_render[source_name] = {
            "generated_root": generated_index,
            "caliper": caliper_matches[0],
            "spin_geometry": spin_matches[0],
        }

    old_root["name"] = "RecoveredStaticRender"
    old_root["children"] = [
        int(child)
        for child in old_root.get("children", [])
        if int(child) not in generated_root_indices
    ]
    for generated_index in generated_root_indices:
        nodes[generated_index]["children"] = []

    source_index: dict[int, int] = {}
    runtime_nodes: list[dict[str, Any]] = list(runtime.get("nodes", []))
    for entry in runtime_nodes:
        source_node: dict[str, Any] = {"name": str(entry.get("name", ""))}
        position = list(entry.get("local_position_m", [0.0, 0.0, 0.0]))
        rotation = list(entry.get("local_rotation_xyzw", [0.0, 0.0, 0.0, 1.0]))
        scale = list(entry.get("local_scale", [1.0, 1.0, 1.0]))
        if not _is_default(position, [0.0, 0.0, 0.0]):
            source_node["translation"] = position
        if not _is_default(rotation, [0.0, 0.0, 0.0, 1.0]):
            source_node["rotation"] = rotation
        if not _is_default(scale, [1.0, 1.0, 1.0]):
            source_node["scale"] = scale
        transform_path_id = int(entry["transform_path_id"])
        source_node["extras"] = {
            "yardman_source_transform_path_id": transform_path_id,
            "yardman_source_game_object_path_id": int(entry["game_object_path_id"]),
            "yardman_source_active": bool(entry.get("active", True)),
            "yardman_source_layer": int(entry.get("layer", 0)),
        }
        source_index[transform_path_id] = len(nodes)
        nodes.append(source_node)

    for entry in runtime_nodes:
        transform_path_id = int(entry["transform_path_id"])
        parent_path_id = int(entry.get("parent_transform_path_id", 0))
        if parent_path_id:
            nodes[source_index[parent_path_id]].setdefault("children", []).append(
                source_index[transform_path_id]
            )

    root_path_id = int(runtime["root_transform_path_id"])
    source_root_index = source_index[root_path_id]
    # Source hierarchy is searched before the render subtree, preventing duplicate
    # render names from becoming semantic authority.
    nodes[source_root_index].setdefault("children", []).append(old_root_index)

    runtime_by_name = {
        str(entry.get("name", "")): entry
        for entry in runtime_nodes
        if str(entry.get("name", "")) in wheel_render
    }
    source_node_by_name = {
        str(entry.get("name", "")): source_index[int(entry["transform_path_id"])]
        for entry in runtime_nodes
        if str(entry.get("name", "")) in wheel_render
    }

    for source_name, render_parts in wheel_render.items():
        pivot_index = source_node_by_name[source_name]
        position = runtime_by_name[source_name]["local_position_m"]
        compensation = [-float(position[0]), -float(position[1]), -float(position[2])]

        caliper_index = render_parts["caliper"]
        geometry_index = render_parts["spin_geometry"]
        nodes[caliper_index]["name"] = "Recovered" + str(nodes[caliper_index].get("name", "Caliper")) + "Geometry"
        nodes[caliper_index]["translation"] = compensation
        nodes[geometry_index]["name"] = "Recovered" + source_name + "Geometry"
        nodes[geometry_index]["translation"] = compensation

        spin_index = len(nodes)
        nodes.append(
            {
                "name": source_name + "Spin",
                "children": [geometry_index],
                "extras": {"yardman_runtime_helper": "wheel_spin"},
            }
        )
        nodes[pivot_index].setdefault("children", []).extend([caliper_index, spin_index])

    document["scenes"] = [{"name": "YardmanSourceVehicle", "nodes": [source_root_index]}]
    document["scene"] = 0
    document.setdefault("asset", {}).setdefault("extras", {})["yardman_source_hierarchy"] = {
        "identity": str(runtime.get("identity", "")),
        "source_unit": str(runtime.get("source_unit", "")),
        "source_nodes": int(runtime.get("source_node_count", 0)),
        "render_source": "flattened_recovery_reanchored",
        "wheel_pivots_reanchored": 4,
        "root_world_transform_normalized": True,
    }
    reachable, orphaned = _validate_single_parent(document)
    document["asset"]["extras"]["yardman_source_hierarchy"].update(
        {"reachable_nodes": reachable, "orphaned_flattened_nodes": orphaned}
    )
    return document


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input_glb", type=Path)
    parser.add_argument("runtime_descriptor", type=Path)
    parser.add_argument("output_glb", type=Path)
    args = parser.parse_args()

    document, chunks = _read_glb(args.input_glb)
    with args.runtime_descriptor.open("r", encoding="utf-8") as handle:
        runtime = json.load(handle)
    reanchor(document, runtime)
    _write_glb(args.output_glb, document, chunks)
    metadata = document["asset"]["extras"]["yardman_source_hierarchy"]
    print(
        "YARDMAN_REANCHOR_GLB_PASS "
        f"identity={metadata['identity']} source={metadata['source_nodes']} "
        f"wheels={metadata['wheel_pivots_reanchored']} "
        f"reachable={metadata['reachable_nodes']} orphaned={metadata['orphaned_flattened_nodes']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
